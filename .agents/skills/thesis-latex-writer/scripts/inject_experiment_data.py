#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
inject_experiment_data.py - Grounded Experiment Data to LaTeX Table Generator

Converts CSV experimental logs into publication-quality GB/T 7713 booktabs three-line tables:
1. True column-wise optimal value bolding (--higher-better / --lower-better).
2. Honest methodology tablenotes generated strictly from companion <csv>.meta.json.
   If no metadata is provided, zero fabricated methodology statements are generated.
3. Provenance tracking: records timestamp, source file path, and SHA-256 hash.
"""

import os
import sys
import csv
import json
import hashlib
import argparse
import datetime

if sys.stdout and hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass


def compute_sha256(file_path):
    h = hashlib.sha256()
    with open(file_path, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()


def parse_numeric(val_str):
    """尝试将带单位或符号的字符串解析为浮点数 (如 '27.2 dB' -> (27.2, ' dB'))。"""
    s = val_str.strip()
    # 纯文本非数字
    if not s or s in ("-", "/", "N/A", "None", "无", "完全消除", "不兼容", "兼容"):
        return None, s

    # 提取开头的浮点数
    import re
    m = re.match(r"^([+-]?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?)\s*(.*)$", s)
    if m:
        try:
            return float(m.group(1)), m.group(2)
        except ValueError:
            pass
    return None, s


def csv_to_booktabs(
    csv_path,
    caption="主要实验定量对比结果",
    label="tab:exp_results",
    higher_better=None,
    lower_better=None,
    meta_path=None
):
    if not os.path.exists(csv_path):
        print(f"[-] CSV file not found: {csv_path}", file=sys.stderr)
        return ""

    csv_sha = compute_sha256(csv_path)

    # 读取 CSV
    rows = []
    with open(csv_path, "r", encoding="utf-8-sig") as fp:
        reader = csv.reader(fp)
        for r in reader:
            if r and any(cell.strip() for cell in r):
                rows.append([cell.strip() for cell in r])

    if len(rows) < 2:
        print("[-] CSV must have at least a header and one data row", file=sys.stderr)
        return ""

    headers = rows[0]
    data = rows[1:]
    col_count = len(headers)

    # 判定各列的最优方向
    # higher_better: list of column names or 0-indexed indices
    # lower_better: list of column names or 0-indexed indices
    col_direction = {}  # col_idx -> 'higher' | 'lower' | 'none'
    higher_set = set(higher_better or [])
    lower_set = set(lower_better or [])

    for c_idx, h in enumerate(headers):
        h_clean = h.strip()
        if str(c_idx) in higher_set or h_clean in higher_set:
            col_direction[c_idx] = "higher"
        elif str(c_idx) in lower_set or h_clean in lower_set:
            col_direction[c_idx] = "lower"
        else:
            # 智能启发式推断
            h_lower = h_clean.lower()
            if any(k in h_lower for k in ("psnr", "ssim", "accuracy", "acc", "mAP", "gain", "rate", "throughput")):
                col_direction[c_idx] = "higher"
            elif any(k in h_lower for k in ("delay", "latency", "time", "loss", "err", "flops", "cost")):
                col_direction[c_idx] = "lower"
            else:
                col_direction[c_idx] = "none"

    # 计算各列数值极值
    col_best_val = {}
    for c_idx in range(1, col_count):
        direction = col_direction.get(c_idx, "none")
        if direction == "none":
            continue
        vals = []
        for r_idx, row in enumerate(data):
            if c_idx < len(row):
                num, _ = parse_numeric(row[c_idx])
                if num is not None:
                    vals.append(num)
        if vals:
            col_best_val[c_idx] = max(vals) if direction == "higher" else min(vals)

    # 查找伴生元数据
    meta_info = None
    candidate_meta = meta_path or (csv_path + ".meta.json")
    if os.path.exists(candidate_meta):
        try:
            with open(candidate_meta, "r", encoding="utf-8") as mfp:
                meta_info = json.load(mfp)
        except Exception as e:
            print(f"[-] Warning: Failed to parse companion metadata {candidate_meta}: {e}", file=sys.stderr)

    # 渲染 LaTeX 代码
    col_align = "l" + "c" * (col_count - 1)
    latex = []
    latex.append(f"% -----------------------------------------------------------------------------")
    latex.append(f"% Provenance: Generated by inject_experiment_data.py")
    latex.append(f"% Source CSV: {os.path.basename(csv_path)} (SHA256: {csv_sha[:16]}...)")
    latex.append(f"% Timestamp : {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    latex.append(f"% -----------------------------------------------------------------------------")
    latex.append("\\begin{table}[htbp]")
    latex.append("  \\centering")
    latex.append(f"  \\caption{{{caption}}}")
    latex.append(f"  \\label{{{label}}}")
    latex.append("  \\small")
    latex.append(f"  \\begin{{tabular*}}{{\\textwidth}}{{@{{\\extracolsep{{\\fill}}}}{col_align}@{{}}}}")
    latex.append("    \\toprule")

    # 表头
    formatted_headers = [f"\\textbf{{{h}}}" for h in headers]
    latex.append("    " + " & ".join(formatted_headers) + " \\\\")
    latex.append("    \\midrule")

    # 数据行：严格仅对最优值加粗
    for row in data:
        while len(row) < col_count:
            row.append("-")
        row_cells = []
        for c_idx in range(col_count):
            cell = row[c_idx]
            if c_idx == 0:
                row_cells.append(cell)
            else:
                best = col_best_val.get(c_idx)
                num, suffix = parse_numeric(cell)
                if best is not None and num is not None and abs(num - best) < 1e-6:
                    row_cells.append(f"\\textbf{{{cell}}}")
                else:
                    row_cells.append(cell)
        latex.append("    " + " & ".join(row_cells) + " \\\\")

    latex.append("    \\bottomrule")
    latex.append("  \\end{tabular*}")

    # 表注：严格根据元数据生成，禁止捏造
    notes = ["加粗字体表示该指标在各基准下的最优值。"]
    if meta_info:
        parts = []
        if "device" in meta_info or "hardware" in meta_info:
            hw = meta_info.get("device") or meta_info.get("hardware")
            parts.append(f"测试硬件环境：{hw}")
        if "repeats" in meta_info:
            parts.append(f"独立测试重复 {meta_info['repeats']} 次取均值")
        if "seed" in meta_info:
            parts.append(f"随机数种子 seed={meta_info['seed']}")
        if parts:
            notes.append("；".join(parts) + "。")

    latex.append("  \\begin{tablenotes}")
    latex.append("    \\footnotesize")
    for n in notes:
        latex.append(f"    \\item[注] {n}")
    latex.append("  \\end{tablenotes}")
    latex.append("\\end{table}")

    return "\n".join(latex)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Convert experiment CSV to GB/T 7713 booktabs table")
    parser.add_argument("csv_file", type=str, help="Input CSV path")
    parser.add_argument("--caption", type=str, default="主要实验定量对比结果", help="Table caption")
    parser.add_argument("--label", type=str, default="tab:exp_results", help="Table LaTeX label")
    parser.add_argument("--higher-better", type=str, default="", help="Comma-separated column names or indices where higher is better")
    parser.add_argument("--lower-better", type=str, default="", help="Comma-separated column names or indices where lower is better")
    parser.add_argument("--meta", type=str, default=None, help="Path to companion metadata JSON file")

    args = parser.parse_args()
    hb = [c.strip() for c in args.higher_better.split(",") if c.strip()]
    lb = [c.strip() for c in args.lower_better.split(",") if c.strip()]

    code = csv_to_booktabs(
        args.csv_file,
        caption=args.caption,
        label=args.label,
        higher_better=hb,
        lower_better=lb,
        meta_path=args.meta
    )
    print(code)
